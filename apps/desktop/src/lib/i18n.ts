export type TranslationKey = keyof typeof translations;
export type TranslationVars = Record<string, string | number>;

export function translate(
  lang: Language,
  key: TranslationKey,
  vars?: TranslationVars,
): string {
  const entry = translations[key];
  let text: string = lang === "tr" ? entry[0] : entry[1];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
    // İngilizcede sayı 1 iken çoğul eklerini tekil hale getir.
    if (lang === "en" && Number(vars.count) === 1) {
      text = singularizeEnglish(text);
    }
  }
  return text;
}

function singularizeEnglish(text: string): string {
  return text
    .replace(/\bthreats are\b/g, "threat is")
    .replace(/\bthreats\b/g, "threat")
    .replace(/\brecords\b/g, "record")
    .replace(/\bfiles\b/g, "file")
    .replace(/\bentries\b/g, "entry")
    .replace(/\bengines\b/g, "engine")
    .replace(/\bevents\b/g, "event")
    .replace(/\bscans\b/g, "scan");
}

export function relativeTime(iso: string, lang: Language): string {
  const date = new Date(iso).getTime();
  if (Number.isNaN(date)) return "—";
  const diff = Math.max(0, Date.now() - date);
  const minutes = Math.floor(diff / 60_000);
  if (minutes < 1) return translate(lang, "time.justNow");
  if (minutes < 60) return translate(lang, "time.minuteAgo", { count: minutes });
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return translate(lang, "time.hourAgo", { count: hours });
  return translate(lang, "time.dayAgo", { count: Math.floor(hours / 24) });
}
